#!/usr/bin/env node
/**
 * Build `client.js` from `src/core.js`, `src/i18n.js`, and `src/main.js`.
 *
 * The Client artifact DSH loads is one script that calls
 * `window.__ModuleLoader__.load({ id, factory })`. The factory body is a plain
 * closure, so the three source files are concatenated verbatim: `core.js` and
 * `i18n.js` declare helpers, `main.js` declares the plugin object the factory
 * returns.
 *
 * `--check` verifies the committed artifact is current (used by `npm run check`).
 */

import { readFile, writeFile, stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

function fail(message) {
  console.error('[build] ' + message)
  process.exit(1)
}

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

/* ------------------------------------------------------------ manifest checks */

const requiredExports = { '.': './index.js', './client': './client.js', './icon': './icon.svg' }
for (const [key, value] of Object.entries(requiredExports)) {
  if (!pkg.exports || pkg.exports[key] !== value) fail(`package.json exports["${key}"] must be "${value}"`)
}
if (!pkg.exports['./locale/*.json']) fail('package.json exports["./locale/*.json"] is missing')
if (!pkg.dsh || !pkg.dsh.bundle || pkg.dsh.bundle.patch !== './cordis.patch.yml') fail('package.json dsh.bundle.patch is missing')
if (!pkg.dsh.client || pkg.dsh.client.platform !== 'web') fail('package.json dsh.client.platform must be "web"')
if (!Array.isArray(pkg.dsh.client.inject) || pkg.dsh.client.inject.length === 0) fail('package.json dsh.client.inject is empty')

const expectedFiles = ['index.js', 'client.js', 'cordis.patch.yml', 'icon.svg', 'locale/zh.json', 'locale/en.json', 'README.md', 'LICENSE']
if (!Array.isArray(pkg.files)) fail('package.json files is missing')
for (const entry of expectedFiles) {
  const patterns = pkg.files
  const covered = pkg.files.some((pattern) => {
    const clean = String(pattern).replace(/\/$/, '')
    if (clean === entry) return true
    if (clean.endsWith('/*')) {
      const base = clean.slice(0, -2)
      return entry === base || entry.startsWith(base + '/')
    }
    return entry.startsWith(clean + '/')
  })
  if (!covered) fail(`package.json files does not cover ${entry}`)
}

/* -------------------------------------------------------------- locale checks */

for (const locale of ['zh', 'en']) {
  const file = path.join(root, 'locale', locale + '.json')
  let parsed
  try {
    parsed = JSON.parse(await readFile(file, 'utf8'))
  } catch (err) {
    fail(`locale/${locale}.json is not valid JSON: ${err.message}`)
  }
  if (!parsed.meta || typeof parsed.meta.title !== 'string' || !parsed.meta.title) fail(`locale/${locale}.json meta.title is missing`)
  if (typeof parsed.meta.description !== 'string' || !parsed.meta.description) fail(`locale/${locale}.json meta.description is missing`)
  if (parsed.meta.detail !== undefined) fail(`locale/${locale}.json meta.detail must stay unset until docs/DETAIL.md exists`)
}

/* ---------------------------------------------------------------- icon check */

const iconInfo = await stat(path.join(root, 'icon.svg'))
if (iconInfo.size > 256 * 1024) fail('icon.svg exceeds 256 KiB')

/* ------------------------------------------------------------------- concat */

const sources = ['core.js', 'i18n.js', 'main.js']
const parts = []
for (const name of sources) {
  const text = await readFile(path.join(root, 'src', name), 'utf8')
  if (/(?:^|\n)[ \t]*(?:import|export)[ \t]/.test(text)) fail(`src/${name} must stay a plain script fragment (found import/export)`)
  parts.push(text.replace(/\s+$/, ''))
}

const banner = [
  '/* Generated by scripts/build.mjs from src/{core,i18n,main}.js — do not edit by hand. */',
  '/* eslint-disable */'
].join('\n')

const artifact = [
  banner,
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory(require) {',
  "    'use strict'",
  '',
  parts.join('\n\n'),
  '',
  '    return CS_PLUGIN',
  '  }',
  '})',
  ''
].join('\n')

const target = path.join(root, 'client.js')

if (checkOnly) {
  let current = ''
  try {
    current = await readFile(target, 'utf8')
  } catch (err) {
    fail('client.js is missing; run `npm run build`')
  }
  if (current.replace(/\r\n/g, '\n') !== artifact) fail('client.js is stale; run `npm run build`')
  console.log('[build] client.js is up to date (' + artifact.length + ' bytes)')
} else {
  await writeFile(target, artifact, 'utf8')
  console.log('[build] wrote client.js (' + artifact.length + ' bytes)')
}
